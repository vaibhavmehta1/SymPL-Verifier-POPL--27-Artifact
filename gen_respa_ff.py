import time
from sage.all import diff, sqrt
from symplectic_verifier import Context, Verifier, Assign, While, Seq

NAT = 6            # atoms in the 1-D chain
N   = 4            # inner fast steps, dt = h/N
EXCL = 2           # exclude nonbonded pairs with |i-j| <= EXCL (1-2 bond, 1-3 angle)

names_q = ["q%d"%i for i in range(1,NAT+1)]
names_p = ["p%d"%i for i in range(1,NAT+1)]
chg     = ["Q%d"%i for i in range(1,NAT+1)]
ctx = Context(names_q+names_p, ["h","k","b","eps","sg","ke"]+chg)
Q = ctx.coords[:NAT]; P = ctx.coords[NAT:2*NAT]
h,k,b,eps,sg,ke = (ctx.param(n) for n in ["h","k","b","eps","sg","ke"])
QC = [ctx.param(c) for c in chg]

# fast: harmonic bonds between consecutive atoms
Vfast = sum((Q[i+1]-Q[i]-b)**2 for i in range(NAT-1)) * (k/2)
# slow: Lennard-Jones + Coulomb over nonbonded pairs (|i-j| > EXCL)
pairs = [(i,j) for i in range(NAT) for j in range(i+1,NAT) if j-i > EXCL]
def lj(i,j):
    u = sg**2/((Q[j]-Q[i])**2); return 4*eps*(u**6 - u**3)
def coul(i,j):
    return ke*QC[i]*QC[j]/sqrt((Q[j]-Q[i])**2)
Vslow = sum(lj(i,j) for i,j in pairs) + sum(coul(i,j) for i,j in pairs)

gf=[diff(Vfast,x) for x in Q]; gs=[diff(Vslow,x) for x in Q]
dt=h/N
slow = Assign(names_p, [P[i]-(h/2)*gs[i] for i in range(NAT)])
body = Seq(Assign(names_p, [P[i]-(dt/2)*gf[i] for i in range(NAT)]),
           Assign(names_q, [Q[i]+dt*P[i] for i in range(NAT)]),
           Assign(names_p, [P[i]-(dt/2)*gf[i] for i in range(NAT)]))
prog = Seq(slow, While(N, body), slow)
omega = ctx.zero()
for i in range(NAT): omega = omega + ctx.dx(names_q[i]).wedge(ctx.dx(names_p[i]))

t0=time.time()
ok,_,resid = Verifier(ctx).verify(omega, prog, omega, verbose=False)
print("%d atoms, %d nonbonded LJ+Coulomb pairs, N=%d : %s  (%.1fs)" %
      (NAT, len(pairs), N, "VERIFIED" if ok else "FAILED", time.time()-t0))

# ---------------------------------------------------------------------------
# emit a human-readable .spec
def e(x): return str(x).replace('^','**')
def tup(nm, ex):
    return "    (%s) := (\n        %s\n    )" % (", ".join(nm),
            ",\n        ".join(e(v) for v in ex))
slow_s  = tup(names_p, [P[i]-(h/2)*gs[i] for i in range(NAT)])
fk_s    = tup(names_p, [P[i]-(dt/2)*gf[i] for i in range(NAT)])
drift_s = tup(names_q, [Q[i]+dt*P[i] for i in range(NAT)])
pre = " + ".join("d%s ^ d%s"%(names_q[i],names_p[i]) for i in range(NAT))
pairs_str = ", ".join("%d-%d"%(i+1,j+1) for i,j in pairs)

hdr = '''# RESPA / r-RESPA multiple-time-stepping for a classical molecular-dynamics
# FORCE FIELD: harmonic bonds (fast) + Lennard-Jones + Coulomb (slow).
#
# A 1-D chain of {NAT} atoms with the standard biomolecular force-field potential
#   V = (k/2) sum_bonds (q_{{i+1}} - q_i - b)^2                       (bonds, FAST)
#     + sum_nonbonded 4 eps ((sg/r_ij)^12 - (sg/r_ij)^6)             (Lennard-Jones)
#     + sum_nonbonded ke q_i q_j / r_ij                              (Coulomb)
# i.e. the bonded + van der Waals + electrostatic terms of the AMBER/CHARMM/OPLS
# form (here without angles/dihedrals).  r_ij = sqrt((q_j - q_i)^2); each atom i
# carries a charge Q_i.  Nonbonded pairs exclude 1-2 (bond) and 1-3 (angle)
# neighbours, i.e. |i-j| > {EXCL}; the {NP} nonbonded pairs are: {PAIRS}.
#
# r-RESPA evaluates the expensive nonbonded force (LJ + Coulomb) once per long
# step h while resolving the stiff bonded force on dt = h/{N}:
#       slow half-kick (h/2)
#       while^{N}:  fast bonded leapfrog, inner step dt = h/{N}
#       slow half-kick (h/2)
# Every kick is the exact gradient of its potential (symplectic shear); the
# verifier pulls the canonical form sum_i dq_i^dp_i back through the whole map
# and confirms it is preserved -- so this multiple-time-stepping MD integrator
# is symplectic.  Forces below were generated by symbolic differentiation.
#
# Refs (full system + integrator):
#   * Force-field form: W. D. Cornell et al. (AMBER), "A Second Generation Force
#     Field for the Simulation of Proteins, Nucleic Acids, and Organic
#     Molecules", J. Am. Chem. Soc. 117, 5179-5197 (1995), Eq. 1;
#   * r-RESPA: M. Tuckerman, B. J. Berne & G. J. Martyna, J. Chem. Phys. 97,
#     1990-2001 (1992);
#   * LJ + electrostatics multiple-time-stepping: P. Procacci, M. Marchi &
#     G. J. Martyna, J. Chem. Phys. 108, 8799 (1998).

coords {QS} {PS}
params h k b eps sg ke {CHG}

pre  {PRE}
post {PRE}

program {{
    # ---- slow half-kick: Lennard-Jones + Coulomb nonbonded force (h/2) ----
{SLOW}

    while^{N} {{
        # ---- fast half-kick: harmonic bond force (dt/2) ----
{FK}

        # ---- drift (dt = h/{N}) ----
{DR}

        # ---- fast half-kick: harmonic bond force (dt/2) ----
{FK}
    }}

    # ---- slow half-kick: Lennard-Jones + Coulomb nonbonded force (h/2) ----
{SLOW}
}}
'''.format(NAT=NAT, EXCL=EXCL, NP=len(pairs), PAIRS=pairs_str, N=N,
           QS=" ".join(names_q), PS=" ".join(names_p), CHG=" ".join(chg),
           PRE=pre, SLOW=slow_s, FK=fk_s, DR=drift_s)
open("examples/respa_forcefield.spec","w").write(hdr)
print("wrote examples/respa_forcefield.spec")
