"""
gen_scaling.py
==============

Generate DIMENSION-SCALING benchmarks for the five textbook integrators, in two
variants of a harmonic test system:

  * regular  -- N INDEPENDENT harmonic oscillators (the textbook H1 repeated):
                    H = sum_i [ p_i^2/2 + q_i^2/2 ],      V'_i = q_i.
                The degrees of freedom never interact, so an implicit method's
                stage Jacobian is block-diagonal.

  * coupled  -- an N-DOF harmonic CHAIN with nearest-neighbour springs:
                    H = sum_i [ p_i^2/2 + q_i^2/2 ] + (k/2) sum_i (q_{i+1}-q_i)^2,
                    V'_i = q_i + k(q_i - q_{i-1}) + k(q_i - q_{i+1}).
                The dimensions genuinely interact, so D = 2N is a real
                high-dimensional problem rather than N disconnected copies.

Running both lets the plot compare how coupling changes the cost-vs-dimension
curve (especially for the implicit methods, whose solve decouples in the regular
case).  Because the per-DOF physics is fixed (linear) and only the DIMENSION
changes, this isolates the scaling signal.  One spec per (variant, method, N) is
written to examples/benchmarks/scaling/, named "<variant>_<method>_chain<NN>.spec".

Run:  sage -python gen_scaling.py
"""

import os

OUTDIR = os.path.join("examples", "benchmarks", "scaling")

VARIANTS = ["coupled", "regular"]

# Degrees of freedom swept per method.  EVERY method/variant gets the full
# ladder; the runner auto-skips dimensions past the first timeout, so each
# (method, variant) sweep runs "up to N=256 or until it walls" on its own.
# This isolates the scaling signal -- and reveals that the implicit methods
# decouple in the regular (independent-oscillator) case, so their stage Jacobian
# becomes block-diagonal and they stay cheap to much higher N than in the
# coupled (interacting-chain) case, where they wall early.
_LADDER = [2, 4, 8, 16, 32, 64, 128, 256]
DIMS = {m: {"coupled": _LADDER, "regular": _LADDER}
        for m in ("symplectic_euler", "leapfrog", "stormer_verlet",
                  "implicit_midpoint", "gl2")}

LABEL = {
    "symplectic_euler":  "symplectic Euler",
    "leapfrog":          "leapfrog (KDK)",
    "stormer_verlet":    "Stoermer-Verlet (DKD)",
    "implicit_midpoint": "implicit midpoint",
    "gl2":               "Gauss-Legendre 2 (GL-2)",
}


def force(prefix, i, N, coupled):
    """Force V'_i over coordinate names prefix1..prefixN.

    Regular: V'_i = q_i.  Coupled: add the nearest-neighbour spring terms.
    """
    t = ["{}{}".format(prefix, i)]
    if coupled:
        if i > 1:
            t.append("k*({p}{i} - {p}{j})".format(p=prefix, i=i, j=i - 1))
        if i < N:
            t.append("k*({p}{i} - {p}{j})".format(p=prefix, i=i, j=i + 1))
    return " + ".join(t)


def names(prefix, N):
    return ["{}{}".format(prefix, i) for i in range(1, N + 1)]


def tup(targets, exprs, indent="    "):
    return "{ind}({t}) := (\n{ind}    {e}\n{ind})".format(
        ind=indent, t=", ".join(targets),
        e=",\n{}    ".format(indent).join(exprs))


def canon_form(N):
    return " + ".join("dq{i} ^ dp{i}".format(i=i) for i in range(1, N + 1))


def header(method, N, coupled):
    if coupled:
        sys_desc = ("coupled harmonic chain: V'_i = q_i + k(q_i-q_{i-1}) + "
                    "k(q_i-q_{i+1})\n#   (nearest-neighbour springs; the DOFs "
                    "interact).")
    else:
        sys_desc = ("regular harmonic oscillators: V'_i = q_i\n#   (N "
                    "independent DOFs; no coupling).")
    return (
        "# Dimension-scaling benchmark: {label}\n"
        "# System: {sysd}\n"
        "#\n"
        "# N = {N} degrees of freedom  (phase-space dimension D = {D}).  Auto-\n"
        "# generated by gen_scaling.py to measure how verification cost grows\n"
        "# with dimension.\n"
    ).format(label=LABEL[method], sysd=sys_desc, N=N, D=2 * N)


def body_symplectic_euler(N, coupled):
    q, p = names("q", N), names("p", N)
    kick = tup(p, ["{} - h*({})".format(p[i], force("q", i + 1, N, coupled)) for i in range(N)])
    drift = tup(q, ["{} + h*{}".format(q[i], p[i]) for i in range(N)])
    return "program {{\n{}\n{}\n}}\n".format(kick, drift)


def body_leapfrog(N, coupled):
    q, p = names("q", N), names("p", N)
    half = tup(p, ["{} - (h/2)*({})".format(p[i], force("q", i + 1, N, coupled)) for i in range(N)])
    drift = tup(q, ["{} + h*{}".format(q[i], p[i]) for i in range(N)])
    return "program {{\n{}\n{}\n{}\n}}\n".format(half, drift, half)


def body_stormer_verlet(N, coupled):
    q, p = names("q", N), names("p", N)
    half = tup(q, ["{} + (h/2)*{}".format(q[i], p[i]) for i in range(N)])
    kick = tup(p, ["{} - h*({})".format(p[i], force("q", i + 1, N, coupled)) for i in range(N)])
    return "program {{\n{}\n{}\n{}\n}}\n".format(half, kick, half)


def body_implicit_midpoint(N, coupled):
    q, p = names("q", N), names("p", N)
    Q, P = names("Q", N), names("P", N)
    a, b = names("a", N), names("b", N)
    init = tup(Q + P, q + p)
    gQ = ["{}/2".format(b[i]) for i in range(N)]
    gP = ["-({})/2".format(force("a", i + 1, N, coupled)) for i in range(N)]
    solve = "    ({u}) := solve ({uu}) -> (\n        {g}\n    )".format(
        u=", ".join(Q + P), uu=", ".join(a + b),
        g=",\n        ".join(gQ + gP))
    upq = tup(q, ["{} + h*{}".format(q[i], P[i]) for i in range(N)])
    upp = tup(p, ["{} - h*({})".format(p[i], force("Q", i + 1, N, coupled)) for i in range(N)])
    return "program {{\n{}\n{}\n{}\n{}\n}}\n".format(init, solve, upq, upp)


def body_gl2(N, coupled):
    q, p = names("q", N), names("p", N)
    Qa, Pa, Qb, Pb = names("Qa", N), names("Pa", N), names("Qb", N), names("Pb", N)
    ga, ra, gb, rb = names("ga", N), names("ra", N), names("gb", N), names("rb", N)
    a11, a12 = "1/4", "(1/4 - sqrt(3)/6)"
    a21, a22 = "(1/4 + sqrt(3)/6)", "1/4"
    init = tup(Qa + Pa + Qb + Pb, q + p + q + p)
    gQa = ["{}*{} + {}*{}".format(a11, ra[i], a12, rb[i]) for i in range(N)]
    gPa = ["-({}*({}) + {}*({}))".format(a11, force("ga", i + 1, N, coupled),
                                         a12, force("gb", i + 1, N, coupled)) for i in range(N)]
    gQb = ["{}*{} + {}*{}".format(a21, ra[i], a22, rb[i]) for i in range(N)]
    gPb = ["-({}*({}) + {}*({}))".format(a21, force("ga", i + 1, N, coupled),
                                         a22, force("gb", i + 1, N, coupled)) for i in range(N)]
    solve = "    ({u}) := solve ({uu}) -> (\n        {g}\n    )".format(
        u=", ".join(Qa + Pa + Qb + Pb),
        uu=", ".join(ga + ra + gb + rb),
        g=",\n        ".join(gQa + gPa + gQb + gPb))
    upq = tup(q, ["{} + h*((1/2)*{} + (1/2)*{})".format(q[i], Pa[i], Pb[i])
                  for i in range(N)])
    upp = tup(p, ["{} - h*((1/2)*({}) + (1/2)*({}))".format(
        p[i], force("Qa", i + 1, N, coupled), force("Qb", i + 1, N, coupled))
        for i in range(N)])
    return "program {{\n{}\n{}\n{}\n{}\n}}\n".format(init, solve, upq, upp)


BUILDERS = {
    "symplectic_euler":  body_symplectic_euler,
    "leapfrog":          body_leapfrog,
    "stormer_verlet":    body_stormer_verlet,
    "implicit_midpoint": body_implicit_midpoint,
    "gl2":               body_gl2,
}


def coords_line(method, N):
    base = names("q", N) + names("p", N)
    if method == "implicit_midpoint":
        base += names("Q", N) + names("P", N)
    elif method == "gl2":
        base += names("Qa", N) + names("Pa", N) + names("Qb", N) + names("Pb", N)
    return "coords " + " ".join(base)


def main():
    if not os.path.isdir(OUTDIR):
        os.makedirs(OUTDIR)
    # clear stale specs so the directory always matches DIMS x VARIANTS
    for stale in os.listdir(OUTDIR):
        if stale.endswith(".spec"):
            os.remove(os.path.join(OUTDIR, stale))
    count = 0
    for variant in VARIANTS:
        coupled = (variant == "coupled")
        params = "params h k" if coupled else "params h"
        for method, vmap in DIMS.items():
            for N in vmap[variant]:
                form = canon_form(N)
                spec = ("{hdr}\n{coords}\n{params}\n\npre  {form}\n"
                        "post {form}\n\n{body}").format(
                    hdr=header(method, N, coupled),
                    coords=coords_line(method, N),
                    params=params,
                    form=form,
                    body=BUILDERS[method](N, coupled))
                path = os.path.join(
                    OUTDIR, "{}_{}_chain{:02d}.spec".format(variant, method, N))
                with open(path, "w") as fh:
                    fh.write(spec)
                count += 1
    print("wrote {} scaling specs ({} x {} methods) in {}".format(
        count, len(VARIANTS), len(DIMS), OUTDIR))


if __name__ == "__main__":
    main()
