from sage.all import diff
from symplectic_verifier import Context

N=4  # inner fast steps
ctx = Context(["q1","q2","q3","q4","p1","p2","p3","p4"], ["h","k","b","eps","sg"])
q1,q2,q3,q4 = ctx.coords[:4]; P=ctx.coords[4:8]; Q=[q1,q2,q3,q4]
h,k,b,eps,sg = (ctx.param(n) for n in ["h","k","b","eps","sg"])
Vfast = (k/2)*((q2-q1-b)**2 + (q3-q2-b)**2 + (q4-q3-b)**2)
def lj(qi,qj):
    u=sg**2/((qj-qi)**2); return 4*eps*(u**6-u**3)
Vslow = lj(q1,q3)+lj(q2,q4)+lj(q1,q4)
gf=[diff(Vfast,x) for x in Q]; gs=[diff(Vslow,x) for x in Q]

def e(expr): return str(expr).replace('^','**')
def tup(names, exprs): return "    (%s) := (\n        %s\n    )" % (
    ", ".join(names), ",\n        ".join(e(x) for x in exprs))

slow = tup(["p1","p2","p3","p4"], [P[i]-(h/2)*gs[i] for i in range(4)])
fk1  = tup(["p1","p2","p3","p4"], [P[i]-(h/(2*N))*gf[i] for i in range(4)])
drift= tup(["q1","q2","q3","q4"], [Q[i]+(h/N)*P[i] for i in range(4)])

header = '''# RESPA / r-RESPA multiple-time-stepping for a realistic molecular-dynamics
# force split: harmonic BONDS (fast) + Lennard-Jones NONBONDED (slow).
#
# A 1-D chain of 4 atoms.  Bonded pairs 1-2, 2-3, 3-4 use a stiff harmonic bond
# (the fast force); the non-bonded pairs 1-3, 2-4, 1-4 use a 12-6 Lennard-Jones
# interaction (the slow force) -- exactly the bonded/nonbonded split that LAMMPS
# (run_style respa), GROMACS and NAMD use to take the cheap-but-stiff bonded
# force on a short timestep and the expensive nonbonded force on a long one.
#
#   V_fast = (k/2) * sum_bonds (q_{i+1} - q_i - b)^2          (harmonic bonds)
#   V_slow = sum_nonbonded 4*eps*((sg/r_ij)^12 - (sg/r_ij)^6) (Lennard-Jones)
#
# Each momentum kick is the exact gradient of its potential (so each kick is a
# symplectic shear), and one outer step of size h is
#       slow half-kick (h/2)
#       while^N:  fast leapfrog with inner step dt = h/N   [N = %d, dt = h/4]
#       slow half-kick (h/2)
# The verifier pulls the canonical form sum_i dq_i^dp_i back through the slow
# kick, the N unrolled fast leapfrogs, and the slow kick, confirming the whole
# multiple-time-stepping map is symplectic.
#
# Forces below were generated by differentiating V_fast, V_slow symbolically.
#
# Ref: M. Tuckerman, B. J. Berne & G. J. Martyna, "Reversible multiple time
#      scale molecular dynamics", J. Chem. Phys. 97, 1990-2001 (1992);
#      LAMMPS run_style respa (Plimpton, J. Comput. Phys. 117, 1 (1995)).

coords q1 q2 q3 q4 p1 p2 p3 p4
params h k b eps sg

pre  dq1 ^ dp1 + dq2 ^ dp2 + dq3 ^ dp3 + dq4 ^ dp4
post dq1 ^ dp1 + dq2 ^ dp2 + dq3 ^ dp3 + dq4 ^ dp4

program {
    # ---- slow half-kick: Lennard-Jones nonbonded force (h/2) ----
%s

    while^%d {
        # ---- fast half-kick: harmonic bond force (dt/2 = h/8) ----
%s

        # ---- drift (dt = h/4) ----
%s

        # ---- fast half-kick: harmonic bond force (dt/2 = h/8) ----
%s
    }

    # ---- slow half-kick: Lennard-Jones nonbonded force (h/2) ----
%s
}
''' % (N, slow, N, fk1, drift, fk1, slow)

open("examples/respa_md.spec","w").write(header)
print("wrote examples/respa_md.spec")
